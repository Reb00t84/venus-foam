print("30а. МНОГОСЛОЙНЫЕ ПАТЧИ (ДЕФОЛТ) -- утечка при N независимых слоёв")
print("-" * 70)
# Дефолтное решение по обшивке -- не монолитное однослойное напыление, а
# сегментированные патчи в неск. слоёв со смещёнными швами (кладка
# вразбежку, как кирпич/черепица/панели реальных оболочек аэростатов --
# см. текст). Если дефекты (пинхолы) в разных слоях не коррелируют по
# положению, проницаемость N слоёв перемножается: та же статистика, что
# оправдывает многослойные барьерные ламинаты в упаковочной индустрии.
# ДОПУЩЕНИЕ независимости слоёв не измерено для этого конкретного случая --
# верхняя граница эффекта, не гарантированное число.
AL_LAYER_MASS_KG = 46.0  # кг на один слой напыления по всей обшивке, из текста выше
N_LAYERS_DEFAULT = 2
for n_layers in (1, 2, 3):
    lo = H2_LOSS_LO * AL_REDUCTION_LO ** n_layers
    hi = H2_LOSS_HI * AL_REDUCTION_HI ** n_layers
    mass_total = AL_LAYER_MASS_KG * n_layers
    tag = " <- дефолт" if n_layers == N_LAYERS_DEFAULT else ""
    print(f"  {n_layers} слой(ев): утечка {lo:.3f}-{hi:.3f} т/год, "
          f"масса напыления {mass_total:.0f} кг{tag}")
print(f"""
При допущении независимости дефектов между слоями уже 2 слоя (дефолт) дают
утечку кратно ниже тонны в год -- на 2-3 порядка меньше однослойной цифры
({h2_metal_1layer_lo:.1f}-{h2_metal_1layer_hi:.1f} т/год), при добавке массы
всего +{AL_LAYER_MASS_KG:.0f} кг (итого {AL_LAYER_MASS_KG*N_LAYERS_DEFAULT:.0f} кг на всю обшивку).
Это ВЕРХНЯЯ ГРАНИЦА эффекта (полная статистическая независимость дефектов
не измерена для данного материала/геометрии патчей), но даже частичная
корреляция оставляет запас на порядки против однослойного случая.
""")

h2_metal_lo = H2_LOSS_LO * AL_REDUCTION_LO ** N_LAYERS_DEFAULT
h2_metal_hi = H2_LOSS_HI * AL_REDUCTION_HI ** N_LAYERS_DEFAULT
