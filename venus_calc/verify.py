# Нижняя атмосфера Венеры близка к сухой адиабате; градиент ~8 K/км в нижних
# ~10 км (VIRA / Seiff 1985). Политропная модель: T(z)=T0-G*z, гидростатика +
# идеальный газ дают P(z)/P0 = (T(z)/T0)^(g*M/(R*G)).
T0_SURF = 735.15         # К, опорный уровень (462 C, как в тексте п. про поверхность)
P0_SURF_BAR = 92.0       # бар, опорный уровень
GAMMA_ADIA = 8.0 / 1000.0  # К/м, адиабатический градиент нижней атмосферы (VIRA)
M_ATM = 0.04345          # кг/моль, средняя молярная масса (96.5% CO2 + 3.5% N2)

expo_baro = G_VENUS * M_ATM / (R * GAMMA_ADIA)

def site_regime(z_km):
    """T (К) и P (бар) на высоте z_km над опорным уровнем по политропной модели."""
    T = T0_SURF - GAMMA_ADIA * z_km * 1000.0
    P = P0_SURF_BAR * (T / T0_SURF) ** expo_baro
    return T, P

