# Свойства CO2 при ~295 К, ~0.49 атм (EngineeringToolbox, см. источники):
# вязкость газа слабо зависит от давления в этом режиме, берём табличное
# значение при атмосферном давлении как оценку
MU_CO2 = 1.5e-5      # Па*с, динамическая вязкость CO2 при ~298 К
K_CO2 = 0.0166        # Вт/(м*К), теплопроводность CO2 при ~298 К
CP_CO2 = 846.0         # Дж/(кг*К), удельная теплоёмкость CO2
RHO_CO2_PLATFORM = 0.89  # кг/м^3, дано в тексте (Среда)
L_PLATFORM = 600.0     # м, характерный размер (диаметр диска)
WIND_LO, WIND_HI = 66.0, 70.0  # м/с, п.19 источников (ВЕГА-1/2)

Pr = CP_CO2 * MU_CO2 / K_CO2
print(f"число Прандтля CO2: {Pr:.3f}")

for wind in (WIND_LO, WIND_HI):
    Re = RHO_CO2_PLATFORM * wind * L_PLATFORM / MU_CO2
    # турбулентная вынужденная конвекция вдоль плоской пластины (Nu = 0.037 Re^0.8 Pr^1/3)
    # ВНИМАНИЕ: корреляция откалибрована для Re до ~10^7-10^8; здесь Re на
    # 1-2 порядка выше -- экстраполяция за пределы проверенного диапазона,
    # число ниже -- ПОРЯДОК ВЕЛИЧИНЫ, не точный расчёт
    Nu = 0.037 * Re ** 0.8 * Pr ** (1 / 3)
    h_conv = Nu * K_CO2 / L_PLATFORM
    print(f"  ветер {wind:.0f} м/с: Re={Re:.2e} (вне калибровки корреляции), "
          f"h_conv~{h_conv:.1f} Вт/(м^2*К)")

h_lo, h_hi = None, None
Re = RHO_CO2_PLATFORM * WIND_LO * L_PLATFORM / MU_CO2
h_hi = 0.037 * Re ** 0.8 * Pr ** (1 / 3) * K_CO2 / L_PLATFORM  # меньше ветра -> меньше h -> больше dT (худший случай)
Re2 = RHO_CO2_PLATFORM * WIND_HI * L_PLATFORM / MU_CO2
h_lo = 0.037 * Re2 ** 0.8 * Pr ** (1 / 3) * K_CO2 / L_PLATFORM

INSOL_LO, INSOL_HI = 520.0, 1300.0  # Вт/м^2, дано в тексте (Среда)
dT_lo = INSOL_LO / h_hi   # мягкий случай: низкая инсоляция, высокий h (сильный ветер)
dT_hi = INSOL_HI / h_lo   # жёсткий случай: высокая инсоляция, низкий h (слабый ветер)
print(f"перепад обшивка-воздух днём (h~{h_lo:.1f}-{h_hi:.1f} Вт/(м^2*К), "
      f"инсоляция {INSOL_LO:.0f}-{INSOL_HI:.0f} Вт/м^2): {dT_lo:.0f}-{dT_hi:.0f} К")

CTE_PTFE = 130e-6  # 1/К, коэффициент линейного расширения PTFE (100-160e-6, середина)
strain_lo = CTE_PTFE * dT_lo * 100
strain_hi = CTE_PTFE * dT_hi * 100
CRACK_STRAIN = 0.75  # %, порог растрескивания Al-барьерного слоя (п.23 источников)
print(f"деформация плёнки от этого перепада: {strain_lo:.2f}-{strain_hi:.2f}% "
      f"(порог растрескивания напыления: {CRACK_STRAIN}%)")
print("""
ВАЖНО: корреляция Nu=0.037*Re^0.8*Pr^1/3 откалибрована для Re до ~10^7-10^8,
здесь Re~10^9-10^10 -- за пределами проверенного диапазона (см. правило 4
CLAUDE.md), результат -- порядок величины, не точное число. Вывод по
порядку: суточный перепад температуры обшивки, если оценка верна хотя бы
по порядку, даёт деформацию плёнки, сопоставимую с порогом растрескивания
напыления (0.75%) уже от одной дневной волны нагрева, без учёта возврата
на холод ночью -- то есть термоциклирование обшивки, а не только ветровая
нагрузка, реальный кандидат на механизм деградации напыления. Нужен точный
расчёт (или лабораторный тест) с корреляцией, валидной в этом диапазоне
Re, прежде чем считать число окончательным.
""")

