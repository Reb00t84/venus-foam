# §32: переход H2 -> воздух растит эквивалентную толщину платформы ~в 2.8 раза
# (11.8-20.5 м -> 33.0-57.5 м). Здесь -- что это делает с ветровой, изгибной
# и плёночной нагрузкой.
h_h2 = thickness_h2_hi          # м, из §32 (верхняя граница массы)
h_air = thickness_air_hi

# --- (1) стационарная ветровая нагрузка на обод ---
# Платформа дрейфует с атмосферой -> набегающий поток ~0. Остаётся сдвиг
# ветра по высоте профиля. Оценка сверху: весь перепад 65-70 км <-> 55.7 км
# (~100 м/с на ~12 км).
SHEAR_PER_M = 100.0 / 12000.0
rho_amb_sep = rho(P_22, T_22K, M_CO2)
def rim_shear_force(h):
    dU = SHEAR_PER_M * h
    A_rim = math.pi * L_PLATFORM * h
    return 0.5 * rho_amb_sep * dU ** 2 * 1.0 * A_rim     # Cd=1
weight_hi = MASS_TOTAL_HIGH * G_VENUS
for label, h in (("H2", h_h2), ("воздух", h_air)):
    print(f"  {label:7s} профиль {h:.1f} м: сдвиговая нагрузка на обод "
          f"{rim_shear_force(h)/1e3:.1f} кН")
print(f"  вертикальные силы станции ~{weight_hi/1e6:.0f} МН -> ветровая доля "
      f"~{rim_shear_force(h_air)/weight_hi*100:.3f}%")

# --- (2) глобальный изгиб: момент тот же, сечение глубже ---
# §54: требуемый несущий слой t ~ M/(sigma*h_disc); момент от распределения
# плавучести/массы, от высоты профиля не зависит, h_disc растёт.
print(f"  несущий слой на глобальный изгиб ~1/h_disc: воздух x{h_h2/h_air:.2f} к H2 "
      f"(глубже сечение -> тоньше слой)")

# --- (3) оболочечная плёнка: площадь стенок ячеек ---
R_CELL_58 = 10.0     # м (как в §54)
def wall_area_factor(h):
    return 2.31 * h / R_CELL_58 + 2.0     # (6*r*h)/(2.598*r^2) + верх/низ
print(f"  площадь оболочечной плёнки: воздух x{wall_area_factor(h_air)/wall_area_factor(h_h2):.2f} к H2")

