import math as _math

def _mode2_lwc_mg_m3(n_cm3, d_um=2.0, rho_droplet=1.8):
    """LWC моды 2 (Knollenberg & Hunten 1980): n [см^-3], d [мкм], rho [г/см^3] -> мг/м^3."""
    r_cm = (d_um / 2) * 1e-4
    vol_cm3 = (4 / 3) * _math.pi * r_cm ** 3
    mass_per_droplet_g = vol_cm3 * rho_droplet
    return n_cm3 * mass_per_droplet_g * 1e9  # г/см^3 -> мг/м^3 (фактор 1e9)

