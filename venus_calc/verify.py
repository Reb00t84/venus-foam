D_DROP = 2.0e-6               # м, мода 2 (Knollenberg & Hunten 1980, как в §25)
RHO_DROP = 1800.0            # кг/м^3 (как в §25)

lam = (MU_CO2_SEP / P_sep_Pa) * math.sqrt(math.pi * R_GAS * T_sep / (2 * M_CO2_KG_MOL))
Kn_drop = 2 * lam / D_DROP
Cc_drop = 1 + Kn_drop * (1.257 + 0.4 * math.exp(-1.1 / Kn_drop))
tau_drop = RHO_DROP * D_DROP ** 2 * Cc_drop / (18 * MU_CO2_SEP)   # время релаксации капли, с
print(f"lambda={lam*1e6:.2f} мкм, Kn={Kn_drop:.2f}, Cc={Cc_drop:.2f}, tau_капли={tau_drop*1e6:.0f} мкс")

def eta_cyl(St):
    """Импакция на цилиндр (нить), фит Landahl-Herrmann для потенциального потока.
    Оптимистичен при низком Re нити (здесь Re~30-60 у тонких нитей -- переходный
    режим, реальный порог Стокса выше). На вывод не влияет: узкое место не тут,
    а в общей эффективности улавливателя (<=20-35%)."""
    return St ** 3 / (St ** 3 + 0.77 * St ** 2 + 0.22)

v_sep = 0.5 * (rel_v_lo + rel_v_hi)     # 32 м/с, из §25
print("одиночная нить, эффективность импакции моды 2:")
for D_wire_um in (50, 100, 200, 500, 1000):
    St_w = tau_drop * v_sep / (D_wire_um * 1e-6)
    print(f"  нить {D_wire_um:4d} мкм: St={St_w:5.1f}  eta_нити={eta_cyl(St_w):.2f}")

# --- (2) общая эффективность улавливателя -- по земным туманоуловителям ---
# ~20% типично, до ~35% предел (Schemenauer & Joe 1989). Их рабочий режим
# 2-10 м/с; здесь 30-34 м/с, вне диапазона -- срыв плёнки/реэнтрейнмент
# ожидаемо снижает эффективность, валидированной модели нет.
ETA_SEP_LO, ETA_SEP_HI = 0.20, 0.35

# --- (3) скорость извлечения ---
w_sep = water_top_kg_m3        # кг/м^3, водность верхнего яруса (мода 2, доля воды 60%), из §25
rate_m2_lo = w_sep * rel_v_lo * ETA_SEP_LO * 86400
rate_m2_hi = w_sep * rel_v_hi * ETA_SEP_HI * 86400
print(f"\nскорость извлечения: {rate_m2_lo:.2f}-{rate_m2_hi:.2f} кг/(м^2*сутки)")
rate_A_lo = rate_m2_lo * A_top_lo
rate_A_hi = rate_m2_hi * A_top_hi
print(f"с сечения §25 ({A_top_lo:.0f}-{A_top_hi:.0f} м^2): {rate_A_lo:.0f}-{rate_A_hi:.0f} кг/сут "
      f"= {rate_A_lo*365/1000:.0f}-{rate_A_hi*365/1000:.0f} т/год")
A_sep_real_lo = A_top_lo / ETA_SEP_HI
A_sep_real_hi = A_top_hi / ETA_SEP_LO
print(f"сечение под валовый спрос ({demand_lo_kg_day:.0f}-{demand_hi_kg_day:.0f} кг/сут) "
      f"при eta {ETA_SEP_LO:.2f}-{ETA_SEP_HI:.2f}: {A_sep_real_lo:.0f}-{A_sep_real_hi:.0f} м^2 "
      f"(сторона {math.sqrt(A_sep_real_lo):.0f}-{math.sqrt(A_sep_real_hi):.0f} м)")

# КОНТРОЛЬ: eta=1 с сечением §25 (пары v как в §25) -> валовый спрос §23.
chk_lo = w_sep * rel_v_hi * 86400 * A_top_lo
chk_hi = w_sep * rel_v_lo * 86400 * A_top_hi
print(f"[контроль] eta=1, сечение §25: {chk_lo:.0f}-{chk_hi:.0f} кг/сут "
      f"(валовый спрос §23: {demand_lo_kg_day:.0f}-{demand_hi_kg_day:.0f})")

print("""
Итог: импакция моды 2 на сетку эффективна (St 3-15 для нитей 0,1-0,5 мм,
eta_нити 0,8-0,95) -- капли ловятся. Узкое место -- ОБЩАЯ эффективность
улавливателя: по земным туманоуловителям <=20-35%, и при 30-34 м/с (втрое-
впятеро выше их режима) вероятно ниже, валидированной модели нет. При
20-35% сечение §25 даёт ~190-605 т/год -- покрывает бытовую потребность
после регенерации (22-152 т/год, §23), но не валовый спрос без регенерации
(1077-1524 т/год): для него сечение в 3-5 раз больше, ~6000-18000 м^2
(сторона ~80-135 м). Оценка занижена: мода 3 (обычно основная масса тумана)
на этих высотах не учтена (нет данных, §25).
""")

