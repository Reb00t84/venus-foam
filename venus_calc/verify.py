#!/usr/bin/env python3
"""
Пена Венеры — проверочный расчётный скрипт.
Пересчитывает все ключевые цифры проекта с нуля, из физических констант
и уже установленных в разборе параметров. Ничего не берётся "на слово" —
если поменяется исходное допущение (высота, КПД, плотность газа), числа
ниже пересчитаются автоматически.
"""

R = 8.314          # универсальная газовая постоянная, Дж/(моль·К)
M_CO2 = 0.044       # кг/моль
M_AIR = 0.029
M_H2 = 0.002
G_VENUS = 8.87      # м/с^2, ускорение свободного падения на Венере (не используется напрямую в лифте, но пригодится)

def rho(P_atm, T_K, M):
    """Плотность газа по уравнению состояния идеального газа."""
    P = P_atm * 101325.0
    return P * M / (R * T_K)

print("=" * 70)
print("1. АТМОСФЕРА ВЕНЕРЫ ПО ВЫСОТЕ (из профиля T/P) и ПОДЪЁМНАЯ СИЛА H2")
print("=" * 70)

# Табличные данные профиля атмосферы (источник: Wikipedia Atmosphere of Venus,
# согласуется с данными зондов)
profile = {
    45: (110 + 273, 1.979),
    50: (75 + 273, 1.066),
    55: (27 + 273, 0.531),
    60: (-10 + 273, 0.236),
    65: (-30 + 273, 0.098),
}

for alt, (T, P) in profile.items():
    rc = rho(P, T, M_CO2)
    rh2 = rho(P, T, M_H2)
    rair = rho(P, T, M_AIR)
    lift_h2 = rc - rh2
    lift_air = rc - rair
    frac = lift_h2 / rc
    print(f"{alt:3d} км: T={T-273:5.1f}C  P={P:.3f} атм  "
          f"rho_CO2={rc:.3f}  подъём H2={lift_h2:.3f} кг/м3  "
          f"подъём возд.={lift_air:.3f} кг/м3  доля_H2={frac*100:.1f}%")

# интерполяция высоты для 22°C между 55 и 60 км
T1, P1, A1 = 27, 0.531, 55
T2, P2, A2 = -10, 0.236, 60
target_T = 22
frac_interp = (T1 - target_T) / (T1 - T2)
alt_22 = A1 + frac_interp * (A2 - A1)
P_22 = P1 - frac_interp * (P1 - P2)
print(f"\nИнтерполяция для 22°C: высота = {alt_22:.2f} км, давление = {P_22:.3f} атм")

T_22K = target_T + 273
rho_co2_22 = rho(P_22, T_22K, M_CO2)
rho_h2_22 = rho(P_22, T_22K, M_H2)
lift_h2_22 = rho_co2_22 - rho_h2_22
frac_h2 = lift_h2_22 / rho_co2_22
print(f"На {alt_22:.2f} км: rho_CO2={rho_co2_22:.3f} кг/м3, "
      f"подъём H2={lift_h2_22:.4f} кг/м3 (доля {frac_h2*100:.2f}%)")

print("\n" + "=" * 70)
print("2. ПЛОЩАДЬ ПЛАТФОРМЫ И БАЗОВАЯ ПАНЕЛЬНАЯ ПЛОЩАДЬ")
print("=" * 70)

AREA_10PCT = 28274.0  # м^2, дано как опорная точка "10% площади"
AREA_TOTAL = AREA_10PCT / 0.10
print(f"Площадь платформы (100%): {AREA_TOTAL:,.0f} м^2")
import math
diameter = 2 * math.sqrt(AREA_TOTAL / math.pi)
print(f"Эквивалентный диаметр диска: {diameter:.0f} м")

print("\n" + "=" * 70)
print("3. ЭНЕРГОБАЛАНС — БАЗОВАЯ ЦЕЛЬ 2 МВт, ЗАМКНУТЫЙ ЦИКЛ ДЕНЬ/НОЧЬ")
print("=" * 70)

TOA = 2601.0          # Вт/м2, солнечная постоянная на орбите Венеры
ETA_PANEL = 0.22
INSOL_LOW, INSOL_HIGH = 0.20, 0.50
ETA_RT = 0.90          # КПД цикла заряд-разряд батареи
T_DAY = 60.0            # часов, символичный день
T_NIGHT = 60.0           # часов, символичная ночь
TARGET_MW = 2.0

I_low = TOA * INSOL_LOW * ETA_PANEL
I_high = TOA * INSOL_HIGH * ETA_PANEL
print(f"Плотность мощности панелей: {I_low:.1f}-{I_high:.1f} Вт/м2")

# День должен покрыть станцию (TARGET*T_DAY) + зарядку ночи (TARGET*T_NIGHT/eta_rt)
E_day_demand = TARGET_MW * T_DAY + (TARGET_MW * T_NIGHT) / ETA_RT
P_day_avg_needed = E_day_demand / T_DAY
print(f"Нужно в среднем днём: {P_day_avg_needed:.3f} МВт "
      f"(станция {TARGET_MW} МВт + подзарядка ночи с учётом {ETA_RT*100:.0f}% КПД)")

area_frac_low = (P_day_avg_needed * 1e6) / (AREA_TOTAL * I_high)   # хорошая инсоляция -> меньше площади
area_frac_high = (P_day_avg_needed * 1e6) / (AREA_TOTAL * I_low)   # плохая инсоляция -> больше площади
print(f"Требуемая доля площади платформы под панели: "
      f"{area_frac_low*100:.1f}%-{area_frac_high*100:.1f}%")
area_needed_low = area_frac_low * AREA_TOTAL
area_needed_high = area_frac_high * AREA_TOTAL
print(f"  = {area_needed_low:,.0f}-{area_needed_high:,.0f} м^2")

print("\n" + "=" * 70)
print("4. БАТАРЕЯ ДЛЯ БАЗОВОЙ ЦЕЛИ (2 МВт, 2-3 суток ночи), ЛИТИЙ-ИОН")
print("=" * 70)

PACK_WH_KG = 149.0     # реальный ориентир NASA X-57, пакетный уровень
NIGHT_DAYS_LOW, NIGHT_DAYS_HIGH = 2, 3

for nd in (NIGHT_DAYS_LOW, NIGHT_DAYS_HIGH):
    E_night_MWh = TARGET_MW * nd * 24
    M_batt_t = E_night_MWh * 1000 / PACK_WH_KG  # МВт*ч * 1000 = кВт*ч; /Вт*ч/кг -> кг; /1000 -> тонны
    print(f"Ночь {nd} сут.: энергия {E_night_MWh:.0f} МВт*ч -> масса батареи {M_batt_t:,.0f} т")

# возьмём диапазон
M_batt_low = TARGET_MW * NIGHT_DAYS_LOW * 24 * 1000 / PACK_WH_KG
M_batt_high = TARGET_MW * NIGHT_DAYS_HIGH * 24 * 1000 / PACK_WH_KG

print("\n" + "=" * 70)
print("5. ОБЪЁМ И ПЛОЩАДЬ ПОПЛАВКА БАТАРЕИ (H2, высота 22°C)")
print("=" * 70)

CELL_THICKNESS = 20.0  # м, допущение по толщине ячейки
lift_h2_used = lift_h2_22  # кг/м3 на рабочей высоте

for label, M_t in (("мин (2 сут.)", M_batt_low), ("макс (3 сут.)", M_batt_high)):
    vol = M_t * 1000 / lift_h2_used
    area = vol / CELL_THICKNESS
    print(f"{label}: масса {M_t:,.0f} т -> объём H2 {vol:,.0f} м^3 -> "
          f"площадь обшивки {area:,.0f} м^2 (при толщине {CELL_THICKNESS:.0f} м)")

A_batt_low = M_batt_low * 1000 / lift_h2_used / CELL_THICKNESS
A_batt_high = M_batt_high * 1000 / lift_h2_used / CELL_THICKNESS

print("\n" + "=" * 70)
print("6. ИТОГОВАЯ ПЛОЩАДЬ ПАНЕЛЕЙ И ГЕНЕРАЦИЯ (базовая площадь + поплавок батареи)")
print("=" * 70)

A_total_low = AREA_10PCT + A_batt_low
A_total_high = AREA_10PCT + A_batt_high
print(f"Итоговая площадь панелей: {A_total_low:,.0f}-{A_total_high:,.0f} м^2 "
      f"({A_total_low/AREA_TOTAL*100:.1f}%-{A_total_high/AREA_TOTAL*100:.1f}% платформы)")

G_low = A_total_low * I_low / 1e6
G_high = A_total_high * I_high / 1e6
print(f"Дневная генерация с этой площади: {G_low:.1f}-{G_high:.1f} МВт")

CONV = 1 + 1 / ETA_RT
P_steady_naive_low = G_low / CONV
P_steady_naive_high = G_high / CONV
print(f"'Наивная' устойчивая мощность (если считать, что вся эта площадь "
      f"сглаживается батареей): {P_steady_naive_low:.1f}-{P_steady_naive_high:.1f} МВт")
print("^ ЭТА ЦИФРА ИЗ ПРОШЛОГО ФАЙЛА БЫЛА НЕ САМОСОГЛАСОВАННОЙ. Проверка ниже.")

print("\n" + "=" * 70)
print("7. ПРОВЕРКА НА САМОСОГЛАСОВАННОСТЬ: сходится ли рекурсия")
print("   'больше площади -> больше энергии -> больше батареи -> больше площади'?")
print("=" * 70)

def marginal_gain(I):
    """Сколько м^2 доп. поплавка батареи требует 1 доп. м^2 генерации,
    если ВСЮ дополнительную энергию сглаживать батареей."""
    dP_steady_per_dA = I / (1e6 * CONV)                      # МВт на м^2
    # dE_night = dP_steady * T_NIGHT (МВт*ч); dM = dE_night*1000/PACK_WH_KG (т)
    dM_batt_per_dP = (T_NIGHT * 1000) / PACK_WH_KG
    dA_batt_per_dM = 1000 / lift_h2_used / CELL_THICKNESS
    return dP_steady_per_dA * dM_batt_per_dP * dA_batt_per_dM

for label, I in (("низкая инсоляция", I_low), ("высокая инсоляция", I_high)):
    k = marginal_gain(I)
    verdict = "РАСХОДИТСЯ (k>1)" if k > 1 else "сходится (k<1)"
    print(f"{label}: предельный коэффициент k = {k:.3f} -> {verdict}")

print("""
ВЫВОД: k > 1 в обоих случаях. Каждый добавленный м^2 генерирующей площади,
если его энергию полностью сглаживать батареей на всю ночь, требует БОЛЬШЕ
м^2 нового поплавка батареи, чем сам дал. Процесс расходится, устойчивого
предела для одной платформы при полном сглаживании НЕТ.

Практическое разрешение: не пытаться сглаживать 100% возможной генерации.
Батарея сайзится РОВНО под целевую круглосуточную нагрузку станции (см. п.4),
это самосогласованно и не рекурсивно. Вся площадь СВЕРХ этого (в т.ч. обшивка
батарейного поплавка) считается ДНЕВНЫМ, НЕСГЛАЖЕННЫМ излишком — то есть не
питает больше людей, а питает дневную промышленную нагрузку без накопителя.
""")

print("=" * 70)
print("8. ПРАВИЛЬНЫЕ ЦИФРЫ: одна платформа, устойчивая нагрузка = целевые 2 МВт")
print("=" * 70)

people_low = TARGET_MW * 1000 / 17.0
people_high = TARGET_MW * 1000 / 12.0
print(f"Вместимость ОДНОЙ платформы (по мерке МКС, 12-17 кВт/чел.): "
      f"{people_low:.0f}-{people_high:.0f} человек")

day_needed = P_day_avg_needed
surplus_low = G_low - day_needed  # просто day - (station+recharge)
surplus_high = G_high - day_needed
print(f"Несглаженный дневной излишек (сверх станции+подзарядки): "
      f"{surplus_low:.1f}-{surplus_high:.1f} МВт — доступен для промышленных "
      f"задач, не для доп. населения без отдельной батареи под них.")

print("\n" + "=" * 70)
print("9. СКОЛЬКО ПЛАТФОРМ НУЖНО НА 500 ЧЕЛОВЕК (примерно середина старого диапазона)")
print("=" * 70)
target_people = 500
n_platforms_low = target_people / people_high
n_platforms_high = target_people / people_low
print(f"{target_people} человек = {n_platforms_low:.1f}-{n_platforms_high:.1f} "
      f"платформ такого базового типа (не одна раздутая, а флот)")

print("\n" + "=" * 70)
print("10. ЛИТИЙ — МАССА ИМПОРТА vs МАССА ВСЕЙ БАТАРЕИ")
print("=" * 70)

LI_KG_PER_KWH_LOW, LI_KG_PER_KWH_HIGH = 0.10, 0.15  # частая отраслевая оценка, не жёстко источникованная
for label, M_t in (("мин (2 сут.)", M_batt_low), ("макс (3 сут.)", M_batt_high)):
    E_kwh = M_t * 1000 * PACK_WH_KG / 1000  # (кг)*(Вт*ч/кг)/1000 = кВт*ч
    li_low = E_kwh * LI_KG_PER_KWH_LOW / 1000  # т
    li_high = E_kwh * LI_KG_PER_KWH_HIGH / 1000
    pct_low = li_low / M_t * 100
    pct_high = li_high / M_t * 100
    print(f"{label}: батарея {M_t:,.0f} т, энергия {E_kwh:,.0f} кВт*ч -> "
          f"чистого лития {li_low:,.1f}-{li_high:,.1f} т "
          f"({pct_low:.1f}-{pct_high:.1f}% массы батареи)")

print("""
Вывод: даже если литий на Венере взять негде (см. п.11), импортировать
нужно не 644-966 т готовой батареи, а на два порядка меньше — только
литиевую "начинку" (~10-22 т), если остальные компоненты ячейки
(катод-хозяин, электролит, корпус) собирать/производить на месте.
Это не отменяет необходимость импорта, но кардинально меняет его масштаб.
""")

print("=" * 70)
print("11. МОЖНО ЛИ ДОБЫВАТЬ ЛИТИЙ НА ВЕНЕРЕ — качественный вывод (не расчёт)")
print("=" * 70)
print("""
Литий геохимически концентрируется в дифференцированных, эволюционировавших
породах (пегматиты, глины, рассолы) — НЕ в базальтах океанического типа,
которые как раз и обнаружены на местах посадки "Венера-13/14"/"Вега-2".
Более того: рентгенофлуоресцентные спектрометры, которые летали на этих
станциях, физически не чувствительны к литию (слишком лёгкий элемент для
их метода) — то есть данных по литию на Венере просто нет, и получить их
нынешним типом приборов нельзя в принципе. Прямого ответа "есть/нет" не
существует, но по аналогии с типом породы — шансы на промышленную
концентрацию низкие. Рабочее допущение: литий импортируется, но, по п.10,
это на порядки меньшая по массе статья, чем казалось по общей массе батарей.
""")

print("=" * 70)
print("12. ГЕРМЕТИЧНОСТЬ ГАЗОВЫХ ЯЧЕЕК — количественный разрыв с лучшим аналогом")
print("=" * 70)
record_days = 57 + 7/24 + 38/(24*60)
needed_years = 20  # условный минимум для станции с десятилетиями эксплуатации
needed_days = needed_years * 365
gap = needed_days / record_days
print(f"Лучший реальный аналог (сверхдавленческий стратостат NASA, миссия GUSTO): "
      f"{record_days:.1f} суток непрерывного полёта.")
print(f"Нужно для станции: порядка {needed_years} лет = {needed_days:,.0f} суток.")
print(f"Разрыв: {gap:.0f}x — рекорд короче нужного на срок примерно в {gap:.0f} раз.")
print("Это не решает вопрос герметичности, но переводит его из 'неизвестно' "
      "в 'известный количественный разрыв', и это разрыв на порядки, а не на десятки процентов.")

print("\n" + "=" * 70)
print("13. ПОДЪЁМ ОБРАЗЦА С ПОВЕРХНОСТИ — грубая проверка физики подъёма (не инженерии)")
print("=" * 70)

T_surf = 460 + 273
P_surf_atm = 93
rho_co2_surf = rho(P_surf_atm, T_surf, M_CO2)
rho_h2_surf = rho(P_surf_atm, T_surf, M_H2)
lift_surf = rho_co2_surf - rho_h2_surf
print(f"У поверхности: rho_CO2 = {rho_co2_surf:.1f} кг/м3 (для сравнения, дано в разборе: ~68 кг/м3)")
print(f"Подъёмная сила H2 у поверхности: {lift_surf:.1f} кг/м3 (в {lift_surf/lift_h2_22:.0f} раз "
      f"больше, чем на рабочей высоте платформы, потому что атмосфера у дна "
      f"на порядок плотнее)")

capsule_mass = 50.0  # кг, условная небольшая капсула с образцом
vol_needed = capsule_mass / lift_surf
r_sphere = (3 * vol_needed / (4 * math.pi)) ** (1/3)
print(f"Для капсулы {capsule_mass:.0f} кг нужен шар-баллон объёмом "
      f"{vol_needed:.2f} м^3 (диаметр ~{2*r_sphere:.2f} м) — то есть "
      f"физика подъёма ТРИВИАЛЬНА, ограничитель не в ней.")
print("Реальный ограничитель — тот же, что и везде в разборе: живучесть "
      "электроники/механизма надувания при 460°C на время посадки+раскрытия, "
      "а не подъёмная сила как таковая.")

print("\n" + "=" * 70)
print("14. РАДИАЦИОННОЕ ЭКРАНИРОВАНИЕ — столб атмосферы НАД платформой vs Земля")
print("=" * 70)

# Что имеет значение для экранирования сверху — это масса столба атмосферы
# НАД точкой наблюдения (а не полная масса атмосферы планеты). Масса столба
# на единицу площади = P / g (давление делится на ускорение свободного
# падения, а не наоборот) — это прямое следствие гидростатического
# равновесия: P = (масса столба / площадь) * g.

G_EARTH = 9.81  # м/с^2
P_EARTH_ATM = 1.0
P_PLATFORM_ATM = P_22  # атм, давление на рабочей высоте платформы (из п.1)

def column_mass_g_cm2(P_atm, g):
    """Масса столба атмосферы над точкой, г/см^2."""
    P_pa = P_atm * 101325.0          # Па = Н/м^2
    mass_kg_m2 = P_pa / g            # кг/м^2
    mass_g_cm2 = mass_kg_m2 * 1000 / 1e4   # кг/м2 -> г/м2 (*1000) -> г/см2 (/1e4)
    return mass_g_cm2

col_earth = column_mass_g_cm2(P_EARTH_ATM, G_EARTH)
col_platform = column_mass_g_cm2(P_PLATFORM_ATM, G_VENUS)
ratio = col_platform / col_earth

print(f"Столб атмосферы над уровнем моря на Земле: {col_earth:.1f} г/см^2 "
      f"(1 атм, g={G_EARTH} м/с^2)")
print(f"Столб атмосферы над платформой на Венере: {col_platform:.1f} г/см^2 "
      f"({P_PLATFORM_ATM:.3f} атм на {alt_22:.2f} км, g={G_VENUS} м/с^2)")
print(f"Отношение платформа/Земля: {ratio:.3f} ({ratio*100:.1f}% земного "
      f"экранирования на уровне моря)")
print("""
Важно: значение имеет столб АТМОСФЕРЫ НАД точкой наблюдения, а не полная
масса атмосферы планеты целиком. У Венеры полная атмосфера примерно в 93
раза массивнее земной — но над платформой на высоте 55,7 км лежит только
0,49/92,1 ≈ 0,5% всего этого столба, остальное — ниже точки наблюдения и
для экранирования сверху роли не играет. Итоговое экранирование на
платформе — заметно больше, чем на высоте крейсерского полёта авиалайнера
(~11 км, где столб — порядка 200-250 г/см^2), но меньше земной поверхности.
""")

print("\n" + "=" * 70)
